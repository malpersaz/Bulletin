CREATE TABLE IF NOT EXISTS `mod_settings` (
  `id` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `lang` VARCHAR(10) NOT NULL,
  `title` VARCHAR(255) DEFAULT NULL,
  `description` TEXT DEFAULT NULL,
  `owner_name` VARCHAR(255) DEFAULT NULL,
  `phone` VARCHAR(50) DEFAULT NULL,
  `whatsapp` VARCHAR(50) DEFAULT NULL,
  `email` VARCHAR(255) DEFAULT NULL,
  `office_address` TEXT DEFAULT NULL,
  `work_address` TEXT DEFAULT NULL,
  `map_embed_code` TEXT DEFAULT NULL,
  `google_search_console` VARCHAR(255) DEFAULT NULL,
  `google_analytics` VARCHAR(255) DEFAULT NULL,
  `meta_tags` TEXT DEFAULT NULL,
  `show_logo` ENUM('y', 'n') NOT NULL DEFAULT 'y',
  `logo_path` VARCHAR(500) DEFAULT NULL,
  `favicon_path` VARCHAR(500) DEFAULT NULL,
  `favicon_96` VARCHAR(255) DEFAULT NULL,
  `apple_touch_icon` VARCHAR(255) DEFAULT NULL,
  `site_webmanifest` VARCHAR(255) DEFAULT NULL,
  `manifest_192` VARCHAR(255) DEFAULT NULL,
  `manifest_512` VARCHAR(255) DEFAULT NULL,
  `established_year` YEAR DEFAULT NULL,
  `user_id` INT(11) NOT NULL,
  `site_icon` VARCHAR(500) DEFAULT NULL,
  `logo_type` VARCHAR(50) DEFAULT 'rectangle',
  `logo_symbol` VARCHAR(500) DEFAULT NULL,
  UNIQUE KEY `unique_lang` (`lang`)
) ENGINE=INNODB DEFAULT CHARSET=utf8;
