CREATE TABLE IF NOT EXISTS `mod_page` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `lang` varchar(10) NOT NULL,
  `name` varchar(255) NOT NULL,
  `parent_id` int(11) DEFAULT 0,
  `order` int(11) DEFAULT 0,
  `root` enum('y','n') NOT NULL DEFAULT 'n',
  `status` enum('y','n') NOT NULL DEFAULT 'y',
  `deck` varchar(500) DEFAULT NULL,
  `summary` text DEFAULT NULL,
  `content` longtext DEFAULT NULL,
  `gallery_id` int(11) DEFAULT NULL,
  `file_id` int(11) DEFAULT NULL,
  `seo` varchar(255) NOT NULL,
  `title` varchar(255) DEFAULT NULL,
  `keywords` text DEFAULT NULL,
  `description` text DEFAULT NULL,
  `image` varchar(255) DEFAULT NULL,
  `acl_id` int(11) DEFAULT 0,
  `category_id` int(11) DEFAULT 0,
  `menu` enum('y','n') NOT NULL DEFAULT 'y',
  `user_id` int(11) NOT NULL,
  PRIMARY KEY (`id`),
  INDEX `idx_page_lang_seo` (`lang`, `seo`),
  INDEX `idx_page_parent` (`parent_id`),
  INDEX `idx_page_status` (`status`),
  INDEX `idx_page_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;
