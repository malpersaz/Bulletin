<?php

/**
 * InstallerConfigWriter - Safely updates db.config.php
 */
class InstallerConfigWriter
{
    private $configPath;

    public function __construct($configPath = null)
    {
        $this->configPath = $configPath ?: root_dir . 'config/db.config.local.php';
    }

    /**
     * Updates the database configuration in db.config.php
     *
     * @param array $params [adapter, host, user, pass, database, database_path]
     * @return bool
     */
    public function write(array $params)
    {
        $configDirectory = dirname($this->configPath);
        if (!$this->canWriteConfig($configDirectory)) {
            return false;
        }

        $normalized = $this->normalizeParams($params);
        $adapter = $normalized['adapter'];
        $content = "<?php\n\n";
        $content .= "/**\n * Amed Framework - Generated by Installer\n";
        $content .= " * Date: " . date('Y-m-d H:i:s') . "\n */\n\n";
        $content .= "if (defined('root_dir') === False) exit(':)');\n\n";
        
        $content .= "\$db = array(\n";
        
        if ($adapter === 'PDO_SQLITE') {
            $content .= "    'installed' => array(\n";
            $content .= "        'adapter' => 'PDO_SQLITE',\n";
            $content .= "        'conf' => array(\n";
            $content .= "            'database_path' => " . $this->renderDatabasePathExpression($normalized['database_path']) . ",\n";
            $content .= "        )\n";
            $content .= "    ),\n";
        } else {
            $content .= "    'installed' => array(\n";
            $content .= "        'adapter' => '" . $adapter . "',\n";
            $content .= "        'conf' => array(\n";
            $content .= "            'host' => '" . addslashes($normalized['host']) . "',\n";
            $content .= "            'user' => '" . addslashes($normalized['user']) . "',\n";
            $content .= "            'pass' => '" . addslashes($normalized['pass']) . "',\n";
            $content .= "            'database' => '" . addslashes($normalized['database']) . "',\n";
            $content .= "            'encoding' => 'utf8',\n";
            $content .= "            'collate' => 'utf8_unicode_ci'\n";
            $content .= "        )\n";
            $content .= "    ),\n";
        }

        $content .= ");\n\n";
        
        $content .= "Registry::add('database', 'installed');\n";
        $content .= "Registry::add('db_config', \$db);\n";
        $content .= "unset(\$db);\n";

        return file_put_contents($this->configPath, $content) !== false;
    }

    public function normalizeParams(array $params)
    {
        $adapter = isset($params['adapter']) ? strtoupper(trim((string) $params['adapter'])) : 'PDO_MYSQL';
        if ($adapter !== 'PDO_MYSQL' && $adapter !== 'PDO_SQLITE') {
            throw new InvalidArgumentException('Unsupported database adapter.');
        }

        $normalized = array(
            'adapter' => $adapter,
            'host' => trim((string) ($params['host'] ?? 'localhost')),
            'user' => (string) ($params['user'] ?? ''),
            'pass' => (string) ($params['pass'] ?? ''),
            'database' => trim((string) ($params['database'] ?? '')),
            'database_path' => installer_default_sqlite_path(),
        );

        if ($adapter === 'PDO_SQLITE') {
            $normalized['database_path'] = $this->normalizeSqlitePath((string) ($params['database_path'] ?? installer_default_sqlite_path()));
            return $normalized;
        }

        if ($normalized['host'] === '') {
            $normalized['host'] = 'localhost';
        }

        if ($normalized['database'] === '') {
            throw new InvalidArgumentException('Database name is required for MySQL.');
        }

        return $normalized;
    }

    private function canWriteConfig($configDirectory)
    {
        if (!is_dir($configDirectory) || !is_writable($configDirectory)) {
            return false;
        }

        if (file_exists($this->configPath)) {
            return is_writable($this->configPath);
        }

        return true;
    }

    private function normalizeSqlitePath($path)
    {
        $path = installer_normalize_path_string(trim((string) $path));
        if ($path === '') {
            $path = installer_default_sqlite_path();
        }

        $preferredExternalPath = installer_normalize_path_string(installer_preferred_external_sqlite_path());
        if (
            $path === $preferredExternalPath
            && !installer_sqlite_path_is_preparable($path)
        ) {
            $path = installer_default_sqlite_path();
        }

        $resolvedPath = installer_resolve_sqlite_path($path);
        if ($resolvedPath === '') {
            throw new InvalidArgumentException('SQLite database path is invalid.');
        }

        if (!installer_is_allowed_sqlite_path($resolvedPath)) {
            throw new InvalidArgumentException('SQLite database path is not allowed.');
        }

        return $path;
    }

    private function renderDatabasePathExpression($path)
    {
        if (installer_is_absolute_path($path)) {
            return "'" . addslashes($path) . "'";
        }

        return "root_dir . '" . addslashes($path) . "'";
    }
}
