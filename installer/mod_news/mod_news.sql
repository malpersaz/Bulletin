CREATE TABLE `mod_news` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `lang` varchar(11) NOT NULL,
  `name` varchar(255) NOT NULL,
  `category_id` int(11) NOT NULL,
  `status` enum('y','n') NOT NULL DEFAULT 'y',
  `slider` enum('y','n') NOT NULL DEFAULT 'n',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT NULL,
  `deck` enum('y','n') NOT NULL DEFAULT 'n',
  `summary` text DEFAULT NULL,
  `content` text NOT NULL,
  `seo` varchar(255) NOT NULL,
  `title` varchar(255) NOT NULL,
  `keywords` varchar(255) NOT NULL,
  `description` varchar(255) NOT NULL,
  `gallery_id` int(11) DEFAULT 0,
  `file_id` int(11) DEFAULT 0,
  `image` varchar(255) DEFAULT NULL,
  `acl_id` int(11) DEFAULT 0,
  `video` varchar(255) DEFAULT NULL,
  `view_count` int(11) NOT NULL DEFAULT 0,
  `user_id` int(11) NOT NULL,
  PRIMARY KEY (`id`),
  INDEX `idx_news_lang_seo` (`lang`, `seo`),
  INDEX `idx_news_category` (`category_id`),
  INDEX `idx_news_status` (`status`),
  INDEX `idx_news_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;
